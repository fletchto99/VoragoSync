local Visibility = require("src/visibility")

local function close(actual, expected)
    assert(math.abs(actual - expected) < 1e-8, tostring(actual) .. " ~= " .. expected)
end

local state = Visibility.new()
local function step(delta, active, sampled, autoHide, locked)
    Visibility.advance(state, delta)
    Visibility.update(state, delta, active == true, sampled ~= false, autoHide ~= false, locked ~= false)
end

step(0, false)
assert(state.hidden and state.opacity == 0)
step(0.05, true)
assert(not state.hidden and state.opacity == 0, "activity starts a fade on subsequent draws")
step(0.25, true)
close(state.opacity, 0.25)
step(0.75, true)
assert(state.opacity == 1)
step(20, false)
assert(state.graceRemaining == 5 and state.opacity == 1, "a long inactive frame must not spend the new grace period")
step(4.99, false)
close(state.graceRemaining, 0.01)
assert(state.opacity == 1)
step(0.01, false)
assert(state.opacity == 1 and not state.hidden, "fade-out begins on subsequent draws")
step(0.4, false)
close(state.opacity, 0.6)
step(0.2, true)
close(state.opacity, 0.6)
step(0.4, true)
assert(state.opacity == 1, "returning activity reverses smoothly without restarting opacity")
step(0, false)
step(5, false)
step(1, false)
assert(state.hidden and state.opacity == 0 and state.cooldown == 10)
step(9.99, true)
assert(state.hidden and state.graceRemaining == 0)
Visibility.advance(state, 0.01)
Visibility.advance(state, 0.001)
Visibility.update(state, 0, true, false, true, true)
assert(state.hidden and state.needsSample, "cooldown expiry requires a fresh sample")
step(0, false)
assert(state.hidden and not state.needsSample, "earlier activity must not queue reappearance")
step(0.05, true)
assert(not state.hidden and state.opacity == 0)
step(1, true)
Visibility.unmount(state, true, true)
assert(state.cooldown == 10 and state.opacity == 0 and not state.wasVisible and state.graceRemaining == 0)
Visibility.advance(state, 5)
assert(state.cooldown == 5, "cooldown advances even without rendering or game samples")
step(0, true)
assert(state.hidden)
step(0, false, true, true, false)
assert(not state.hidden and state.opacity == 1, "editing bypasses cooldown")
step(0, false)
step(1, false)
assert(state.hidden)
step(0, false, true, false)
step(1, false, true, false)
assert(not state.hidden and state.opacity == 1, "always-visible mode bypasses cooldown")

state = Visibility.new()
step(0, false, true, true, false)
Visibility.unmount(state, true, false)
assert(state.cooldown == 0, "unloading while editing does not add a cooldown")
step(0, true)
step(1, true)
Visibility.unmount(state, false, true)
assert(state.cooldown == 0, "unloading an always-visible overlay does not add a cooldown")

for _, delta in ipairs({ -1, math.huge, -math.huge, 0 / 0, "1" }) do
    assert(not pcall(Visibility.advance, Visibility.new(), delta))
end
assert(Visibility.new().cooldown == 0, "fresh app instances do not share visibility history")
print("visibility_test.lua: passed")
